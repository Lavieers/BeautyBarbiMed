import puppeteer from 'puppeteer-core'
const browser = await puppeteer.launch({ executablePath: 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe', headless: true })
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
const page = await browser.newPage()
await page.setViewport({ width: 390, height: 844, isMobile: true, hasTouch: true, deviceScaleFactor: 2 })
await page.goto('http://localhost:5173/', { waitUntil: 'networkidle0' })
await sleep(800)
await page.evaluate(() => document.querySelector('#oferta').scrollIntoView()); await sleep(600)
await page.evaluate(() => document.querySelectorAll('.offer__tab')[4].click()); await sleep(900)
await page.evaluate(() => { const c=[...document.querySelectorAll('.pkg-card')].find(x=>x.textContent.includes('PANNY')); c.querySelector('.pkg-card__inner').click() }); await sleep(1000)
await page.screenshot({ path: '.tmp-screens/panny-modal.png' })
await page.keyboard.press('Escape'); await sleep(600)
await page.evaluate(() => document.querySelector('.offer__carousel-wrap').scrollIntoView())
await page.evaluate(() => { const c=[...document.querySelectorAll('.pkg-card')].filter(x=>x.textContent.includes('PANNY'))[1]; c.scrollIntoView({inline:'center', block:'nearest'}) }); await sleep(900)
await page.screenshot({ path: '.tmp-screens/panny-card.png' })
await browser.close()
